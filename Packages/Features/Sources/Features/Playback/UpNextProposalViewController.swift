            eyebrow: nil,
            title: "The Uncommonly Long Episode Title That Wraps to a Second Line Before It Truncates",
            previewImage: nil,
            onPlayNext: {},
        )
        .background(previewBackdrop)
        .ignoresSafeArea()
        .withThemeEnvironment()
    }
